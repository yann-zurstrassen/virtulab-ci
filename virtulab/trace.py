"""`virtulab trace`: record every register access of a run and show it as one page.

Each access is tied to what explains it: the register and its bit fields from the chip
maker's SVD file, the firmware line that made it, and, for VirtuLab's own models, the
model code that answered. Time is the emulator's virtual clock, in milliseconds.
"""

import gzip
import html
import json
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET
from collections import Counter
from dataclasses import replace
from pathlib import Path

from . import MONITOR_MARK, VirtulabError
from .boards import BOARDS
from .build import BuildConfig, build, tool
from .config import ProjectConfig, generated_models, renode_repl

_ACCESS = re.compile(r"\] (\S+): \[cpu: 0x([0-9A-Fa-f]+)\] (Read|Write)(\w+) (?:from|to) 0x([0-9A-Fa-f]+) "
                     r"\(([^)]*)\), (?:value|returned) 0x([0-9A-Fa-f]+)")
_TICK = re.compile(r"VL_MS (\d+)")
# Renode's I2C controllers report each transfer at debug level.
_I2C_START = re.compile(r"\] (i2c\d+): (?:Starting|Restarting) transmission")
_I2C_STOP = re.compile(r"\] (i2c\d+): Stopping transmission")
_I2C_DATA = re.compile(r"\] (i2c\d+): (Writing to|Performed read from) 0x([0-9A-Fa-f]+): \[([^\]]*)\]")
# The SPI multiplexer in front of each SPI bus reports chip-select changes (lines idle high).
_CHIP_SELECT = re.compile(r"\] (spi\d+)\.spi\d+_mux: GPIO #(\d+) set to (True|False)")
# The emulator saying it does not model bits the firmware set.
_UNHANDLED = re.compile(r"\] (\S+): Unhandled (write|read) (?:to|from) offset 0x([0-9A-Fa-f]+)\.(?: Unhandled bits: \[([^\]]*)\])?"
                        r"(?: when writing value 0x([0-9A-Fa-f]+))?\.?(?: Tags: (.*))?")
_ANSI = re.compile(r"\x1b\[[0-9;]*m")
_CONSOLE = {"usart2"}  # the firmware's console on stm32f4_discovery
# Renode names that are not the SVD peripheral of the same name: memories, and the Arm core,
# which the chip maker's SVD file does not describe.
_NOT_IN_SVD = {"flash": "flash memory", "sram": "RAM", "nvic": "Arm core (NVIC, SysTick, system control)"}

_CLOCK_MODEL = """\
// Generated by VirtuLab: marks each millisecond of virtual time in the log, for `virtulab trace`.
using Antmicro.Renode.Core;
using Antmicro.Renode.Logging;
using Antmicro.Renode.Peripherals;
using Antmicro.Renode.Peripherals.Timers;
using Antmicro.Renode.Time;

namespace Antmicro.Renode.Peripherals.VirtuLab
{
    public class TraceClock : IPeripheral
    {
        public TraceClock(IMachine machine)
        {
            timer = new LimitTimer(machine.ClockSource, 1000, this, "trace", 1, Direction.Descending, true, WorkMode.Periodic, true);
            timer.LimitReached += () => { ms++; this.Log(LogLevel.Info, "VL_MS {0}", ms); };
        }

        public void Reset()
        {
        }

        private readonly LimitTimer timer;
        private long ms;
    }
}
"""


# ---------------------------------------------------------------------------
# what the chip maker says the registers are

def load_svd(path: Path) -> dict[str, dict]:
    """Peripheral name -> {base, registers: {offset: {name, description, fields: [...]}}}."""
    raw = gzip.open(path).read() if path.suffix == ".gz" else path.read_bytes()
    root = ET.fromstring(raw)
    peripherals: dict[str, ET.Element] = {p.findtext("name"): p for p in root.iter("peripheral")}
    out = {}
    for name, p in peripherals.items():
        source = peripherals.get(p.get("derivedFrom") or "", p)
        registers = {}
        for r in source.iter("register"):
            fields = [{"name": f.findtext("name"), "offset": int(f.findtext("bitOffset") or 0),
                       "width": int(f.findtext("bitWidth") or 1),
                       "description": " ".join((f.findtext("description") or "").split())}
                      for f in r.iter("field")]
            registers[int(r.findtext("addressOffset"), 0)] = {
                "name": r.findtext("name"), "description": " ".join((r.findtext("description") or "").split()),
                "fields": sorted(fields, key=lambda f: -f["offset"])}
        out[name] = {"base": int(p.findtext("baseAddress"), 0), "registers": registers,
                     "description": " ".join((source.findtext("description") or "").split())}
    return out


def svd_name(renode_name: str) -> str | None:
    """Renode's name for a peripheral, as the SVD file spells it: gpioPortA -> GPIOA, adc1 -> ADC1."""
    if renode_name in _NOT_IN_SVD:
        return None
    if renode_name.startswith("gpioPort"):
        return "GPIO" + renode_name[len("gpioPort"):]
    return renode_name.upper()


def decode(fields: list[dict], value: int) -> list[dict]:
    return [{**f, "value": (value >> f["offset"]) & ((1 << f["width"]) - 1)} for f in fields]


# ---------------------------------------------------------------------------
# reading the run

def parse_log(text: str) -> list[dict]:
    """Register accesses, bus messages and the emulator's notes, in the order they happened."""
    events, now, open_messages = [], 0, {}
    for line in _ANSI.sub("", text).splitlines():
        tick = _TICK.search(line)
        if tick:
            now = int(tick[1])
            continue
        m = _I2C_DATA.search(line)
        if m:
            bus, address = m[1], int(m[3], 16)
            data = [int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]+)", m[4])]
            message = open_messages.get(bus)
            if message is None or message["address"] != address:
                message = {"kind": "bus", "t": now, "bus": bus, "address": address, "write": [], "read": []}
                open_messages[bus] = message
                events.append(message)
            message["write" if m[2] == "Writing to" else "read"].extend(data)
            continue
        m = _I2C_STOP.search(line)
        if m:
            open_messages.pop(m[1], None)
            continue
        m = _CHIP_SELECT.search(line)
        if m:
            events.append({"kind": "select", "t": now, "bus": m[1], "index": int(m[2]), "selected": m[3] == "False"})
            continue
        m = _UNHANDLED.search(line)
        if m:
            events.append({"kind": "unmodelled", "t": now, "peripheral": m[1], "op": m[2], "offset": int(m[3], 16),
                           "bits": m[4] or "", "value": int(m[5], 16) if m[5] else None, "tags": (m[6] or "").strip()})
            continue
        m = _ACCESS.search(line)
        if m:
            events.append({"kind": "access", "t": now, "peripheral": m[1], "pc": int(m[2], 16), "op": m[3].lower(),
                           "width": m[4], "offset": int(m[5], 16), "value": int(m[7], 16)})
    return events


def _locate(elf: Path, pcs: list[int], root: Path) -> dict[int, dict]:
    """One addr2line call for every distinct instruction address."""
    if not pcs:
        return {}
    out = subprocess.run([tool("addr2line"), "-f", "-C", "-e", str(elf), *map(hex, pcs)],
                         capture_output=True, text=True).stdout.splitlines()
    found = {}
    for pc, function, where in zip(pcs, out[0::2], out[1::2]):
        path, _, line = where.split(" ")[0].rpartition(":")
        entry = {"function": None if function == "??" else function}
        if line.isdigit() and path and not path.startswith("??"):
            p = Path(path)
            if p.is_absolute() and p.resolve().is_relative_to(root):
                path = p.resolve().relative_to(root).as_posix()
            entry.update(file=path, line=int(line))
        found[pc] = entry
    return found


def _snippet(text: str, line: int, around: int = 3) -> dict:
    lines = text.splitlines()
    start = max(1, line - around)
    return {"start": start, "line": line, "text": lines[start - 1:min(len(lines), line + around)]}


def _model_line(source: str, offset: int, op: str) -> int | None:
    """In a generated model, the `case` that handles a register offset, in the read or the write method."""
    lines = source.splitlines()
    method = "ReadDoubleWord" if op == "read" else "WriteDoubleWord"
    start = next((n for n, text in enumerate(lines) if f" {method}(" in text), 0)
    for number, text in enumerate(lines, 1):
        m = re.search(r"const long (\w+) = 0x([0-9A-Fa-f]+);", text)
        if m and int(m[2], 16) == offset:
            for case_number in range(start + 1, len(lines) + 1):
                if f"case {m[1]}:" in lines[case_number - 1]:
                    return case_number
            return number
    return None


