# running and writing

def record(cfg: ProjectConfig, root: Path, work: Path, sources: list[str] | None = None,
           include: list[str] | None = None) -> dict:
    from .emulator import run as emulate

    board = BOARDS[cfg.board]
    if board.emulator != "renode":
        raise VirtulabError(f"virtulab trace needs a board with peripherals, such as stm32f4_discovery, "
                            f"not {cfg.board}")
    out = work / "trace"
    shutil.rmtree(out, ignore_errors=True)
    bcfg = BuildConfig(board=board, sources=sources or cfg.sources, include_dirs=include or cfg.include,
                       cflags=cfg.cflags.split(), runtime=cfg.runtime)
    result = build(root, bcfg, out / "build", exclude=work)
    if not result.ok or result.elf is None:
        raise VirtulabError("the firmware did not build:\n" + result.log[-3000:])
    run_dir = out / "run"
    (run_dir / "models").mkdir(parents=True)
    models = generated_models(cfg, root)
    for name, source in {**models, "TraceClock.cs": _CLOCK_MODEL}.items():
        (run_dir / "models" / name).write_text(source)
    description, _, monitor = (renode_repl(cfg, root) or "").partition(MONITOR_MARK)
    repl = (f"vl_trace: VirtuLab.TraceClock\n{description}{MONITOR_MARK}\n"
            f"{monitor}sysbus LogAllPeripheralsAccess true\n")
    buses = sorted({m.bus for m in cfg.modules.values()} | {p.bus for p in cfg.peripherals.values()})
    repl += "".join(f"logLevel 0 {bus}\n" for bus in buses if bus.startswith("i2c"))
    repl += "".join(f"logLevel -1 sysbus.{bus}.{bus}_mux\n" for bus in buses if bus.startswith("spi"))
    ran = emulate(board, result.elf, float(re.sub(r"[^\d.]", "", cfg.timeout) or 30), run_dir, repl)
    events = parse_log((run_dir / "renode.log").read_text(errors="replace"))
    if not any(e["kind"] == "access" for e in events):
        raise VirtulabError("the run recorded no register accesses")

    svd_file = _find_svd()
    chip = load_svd(svd_file) if svd_file else {}
    _name_devices(cfg, events)
    _note_unmodelled(events)
    locations = _locate(result.elf, sorted({e["pc"] for e in events if e["kind"] == "access"}), root)
    files: dict[str, dict] = {}
    for loc in locations.values():
        if "file" in loc and (root / loc["file"]).is_file():
            files.setdefault(loc["file"], {"text": (root / loc["file"]).read_text(errors="replace")})
    generated = {n.removesuffix(".cs"): s for n, s in models.items()}
    for e in events:
        if e["kind"] != "access":
            continue
        e.update(locations.get(e["pc"], {}))
        p = chip.get(svd_name(e["peripheral"]) or "")
        reg = p["registers"].get(e["offset"]) if p else None
        if e["peripheral"] in _NOT_IN_SVD:
            e["note"] = _NOT_IN_SVD[e["peripheral"]] + ": not in the chip's SVD file"
        if reg:
            e["register"] = reg["name"]
            e["fields"] = decode(reg["fields"], e["value"])
        owner = next((a for a in cfg.analog.values() if a.name == e["peripheral"]), None)
        if owner and owner.class_name in generated:
            line = _model_line(generated[owner.class_name], e["offset"], e["op"])
            if line:
                e["model"] = {"file": f"models/{owner.class_name}.cs", "line": line}
                files.setdefault(e["model"]["file"], {"text": generated[owner.class_name], "generated": True})
        e["console"] = e["peripheral"] in _CONSOLE
    events = _serial_messages(cfg, events)
    _decode_catalog(cfg, events)
    registers = {}
    for name in {e["peripheral"] for e in events if e["kind"] == "access"}:
        p = chip.get(svd_name(name) or "")
        if p:
            registers[name] = {"description": p["description"], "base": p["base"],
                               "registers": {o: {k: r[k] for k in ("name", "description")} | {"fields": r["fields"]}
                                             for o, r in p["registers"].items()}}
    catalog = _catalog_links(cfg)
    for name, entry in catalog.items():
        if "source_text" in entry:
            files.setdefault(entry["source"], {"text": entry.pop("source_text"), "generated": False})
    return {
        "catalog": catalog,
        "board": {"name": board.name, "cpu": board.cpu, "description": board.description},
        "modules": [{"name": m.name, "model": m.model, "bus": m.bus} for m in cfg.modules.values()]
                   + [{"name": p.name, "model": "project-defined", "bus": p.bus} for p in cfg.peripherals.values()]
                   + [{"name": a.name, "model": "ADC", "bus": "on chip",
                       "inputs": a.inputs} for a in cfg.analog.values()],
        "svd": svd_file.name if svd_file else None,
        "exit_code": ran.exit_code, "timed_out": ran.timed_out, "output": ran.output[-4000:],
        "duration_ms": max(e["t"] for e in events),
        "counts": dict(Counter(e["peripheral"] for e in events if e["kind"] == "access")),
        "events": events, "registers": registers, "files": files,
    }


def _name_devices(cfg: ProjectConfig, events: list[dict]) -> None:
    """Which device a bus message went to, and for project-defined devices, which registers."""
    from .catalog import get_module
    devices = {}
    for m in cfg.modules.values():
        module = get_module(m.model)
        address = m.address if m.address is not None else module.default_address
        devices[(m.bus, address)] = {"name": m.name, "model": module.title}
    for p in cfg.peripherals.values():
        devices[(p.bus, p.address)] = {"name": p.name, "model": "project-defined", "registers": p.registers,
                                       "little": p.little_endian}
    for e in events:
        if e["kind"] != "bus":
            continue
        device = devices.get((e["bus"], e["address"]))
        e["device"] = device["name"] if device else None
        e["model"] = device["model"] if device else "nothing declared at this address"
        if device and "registers" in device and e["write"]:
            e["decoded"] = _decode_registers(device["registers"], device["little"], e["write"], e["read"])


def _decode_registers(registers, little: bool, written: list[int], read: list[int]) -> list[dict]:
    """A register device: the first byte written selects the register, the rest are its bytes."""
    pointer, data, op = written[0], (written[1:] or read), "write" if written[1:] else "read"
    found = []
    for r in sorted(registers, key=lambda r: r.at):
        if pointer <= r.at and r.at + r.size <= pointer + len(data):
            raw = data[r.at - pointer:r.at - pointer + r.size]
            value = int.from_bytes(bytes(raw), "little" if little else "big")
            found.append({"register": r.name, "op": op, "value": value, "size": r.size})
    return found


def _spi_devices(cfg: ProjectConfig) -> dict[tuple[str, int], str]:
    """(bus, multiplexer index) -> module name, numbered as config.renode_repl numbers them."""
    from .catalog import get_module
    found, count = {}, {}
    for m in cfg.modules.values():
        if get_module(m.model).protocol == "spi":
            found[(m.bus, count.get(m.bus, 0))] = m.name
            count[m.bus] = count.get(m.bus, 0) + 1
    return found


def _serial_messages(cfg: ProjectConfig, events: list[dict]) -> list[dict]:
    """SPI and UART messages, rebuilt from the data-register accesses the firmware made.

    SPI: the bytes written to and read from the bus's DR while one chip select is low make one
    exchange with that device. UART: bytes written to the port's DR go to the device, bytes read
    come from it; a change of direction starts a new message."""
    from .catalog import get_module
    spi = _spi_devices(cfg)
    uart = {m.bus: m.name for m in cfg.modules.values() if get_module(m.model).protocol == "uart"}
    out, selected, open_uart = [], {}, {}
    for e in events:
        out.append(e)
        if e["kind"] == "select":
            if e["selected"]:
                selected[e["bus"]] = {"kind": "bus", "protocol": "spi", "t": e["t"], "bus": e["bus"],
                                      "address": e["index"], "device": spi.get((e["bus"], e["index"])),
                                      "write": [], "read": []}
            else:
                message = selected.pop(e["bus"], None)
                if message and (message["write"] or message["read"]):
                    out.append(message)
            continue
        if e["kind"] != "access" or e.get("register") != "DR":
            continue
        width = 0xFF
        if e["peripheral"] in selected:
            selected[e["peripheral"]]["write" if e["op"] == "write" else "read"].append(e["value"] & width)
        elif e["peripheral"] in uart:
            direction = "write" if e["op"] == "write" else "read"
            message = open_uart.get(e["peripheral"])
            if message is None or message["direction"] != direction:
                message = {"kind": "bus", "protocol": "uart", "t": e["t"], "bus": e["peripheral"], "address": 0,
                           "device": uart[e["peripheral"]], "direction": direction, "write": [], "read": []}
                open_uart[e["peripheral"]] = message
                out.append(message)
            message[direction].append(e["value"] & width)
    for message in out:
        if message["kind"] == "bus" and "model" not in message:
            message["model"] = _model_title(cfg, message.get("device"))
    return out


def _model_title(cfg: ProjectConfig, device: str | None) -> str:
    from .catalog import get_module
    if device in cfg.modules:
        return get_module(cfg.modules[device].model).title
    return "nothing declared here"


# How each catalog model is addressed, and which of its constants name registers or commands.
# The names are the model's own, so a decoded message maps straight to the code that answers it.
_DECODERS = {
    "tmp108": ("pointer", ["TemperatureRegister", "ConfigurationRegister", "LowLimitRegister"]),
    "ina219": ("pointer", ["ConfigurationRegister", "ShuntVoltageRegister", "BusVoltageRegister", "PowerRegister",
                           "CurrentRegister", "CalibrationRegister"]),
    "mpu6050": ("pointer", ["GyroConfig", "AccelConfig", "AccelerationOut", "PowerManagement1", "WhoAmI"]),
    "adxl345": ("spi-address", ["DevId", "BwRate", "PowerCtl", "DataFormat", "DataX0", "DataZ1"]),
    "w25q128": ("instruction", ["WriteEnable", "WriteDisable", "ReadStatus", "ReadData", "PageProgram", "SectorErase",
                                "BlockErase", "ChipErase", "ChipEraseAlternate", "ReadJedecId"]),
    "sht31": ("command16", None),
}
_CONST = re.compile(r"const (?:int|byte|uint) (\w+) = (0x[0-9A-Fa-f]+|\d+);")
_CASE = re.compile(r"case (0x[0-9A-Fa-f]+):")


def _model_names(source: str, names: list[str] | None) -> dict[int, dict]:
    """value -> {name, line} from a model's constants, or from its `case 0x...:` labels."""
    found = {}
    for number, text in enumerate(source.splitlines(), 1):
        if names is None:
            m = _CASE.search(text)
            if m:
                found.setdefault(int(m[1], 16), {"name": None, "line": number})
            continue
        m = _CONST.search(text)
        if m and m[1] in names:
            found.setdefault(int(m[2], 0), {"name": m[1], "line": number})
    return found


def _datasheet_rows(model: str, value: int, width: int) -> list[dict]:
    """Rows of the model's cited datasheet map that state this value, written as 0x.. in their text."""
    from . import datasheets
    if model not in datasheets.available():
        return []
    spellings = {f"0x{value:0{width}X}", f"0x{value:0{width}x}"}
    if width == 4:
        spellings |= {f"0x{value >> 8:02X}{value & 0xFF:02X}"}
    return [{"topic": r["topic"], "source": r.get("source")} for r in datasheets.load(model)["rows"]
            if any(s in str(r.get("datasheet", "")) for s in spellings)]


def _decode_catalog(cfg: ProjectConfig, events: list[dict]) -> None:
    """Name each catalog-sensor message by the model's own register or command, with its code and datasheet."""
    from . import DEVICES_DIR
    from .catalog import get_module
    tables, pointers = {}, {}
    for m in cfg.modules.values():
        decoder = _DECODERS.get(m.model)
        module = get_module(m.model)
        source = DEVICES_DIR / (module.renode_type.split(".")[-1] + ".cs")
        if decoder and source.is_file():
            tables[m.name] = (m.model, decoder[0], _model_names(source.read_text(), decoder[1]), f"devices/{source.name}")
    for e in events:
        if e["kind"] != "bus" or e.get("device") not in tables:
            continue
        model, style, names, file = tables[e["device"]]
        w, r = e["write"], e["read"]
        if style == "pointer":
            if w:
                pointers[e["device"]] = w[0]
            value, width, data = pointers.get(e["device"]), 2, (w[1:] or r)
            op = "write" if w[1:] else "read" if r else "select"
        elif style == "spi-address" and w:
            value, width = w[0] & 0x3F, 2
            op, data = ("read" if w[0] & 0x80 else "write"), (r[1:] if w[0] & 0x80 else w[1:])
        elif style == "instruction" and w:
            # Full duplex: what the firmware sent after the instruction (an address, data) and what
            # came back (an ID, a status, data) are both meaningful, and differ per instruction.
            value, width, op, data = w[0], 2, "instruction", w[1:]
        elif style == "command16" and len(w) >= 2:
            value, width, op, data = (w[0] << 8) | w[1], 4, "command", w[2:]
        else:
            continue
        if value is None:
            continue
        known = names.get(value) if style != "spi-address" else next(
            (v for a, v in sorted(names.items()) if a <= value <= a + (5 if v["name"] == "DataX0" else 0)), None)
        rows = _datasheet_rows(model, value, width)
        e["catalog"] = {"value": f"0x{value:0{width}X}", "op": op, "data": data,
                        "received": r[1:] if style == "instruction" else [],
                        "name": (known or {}).get("name") or (rows[0]["topic"] if rows else None),
                        "model": {"file": file, "line": known["line"]} if known else None,
                        "datasheet": rows[:2]}


def _catalog_links(cfg: ProjectConfig) -> dict[str, dict]:
    """For each catalog module: its model source in VirtuLab and its datasheet documents."""
    from . import DEVICES_DIR, datasheets
    from .catalog import get_module
    links = {}
    for m in cfg.modules.values():
        module = get_module(m.model)
        entry: dict = {"model": module.title}
        source = DEVICES_DIR / (module.renode_type.split(".")[-1] + ".cs")
        if module.renode_type.startswith("VirtuLab.") and source.is_file():
            entry["source"] = f"devices/{source.name}"
            entry["source_text"] = source.read_text()
        if m.model in datasheets.available():
            data = datasheets.load(m.model)
            entry["documents"] = [{"title": d.get("title"), "revision": d.get("revision"), "url": d.get("url")}
                                  for d in data["documents"]]
        links[m.name] = entry
    return links


def _note_unmodelled(events: list[dict]) -> None:
    """Attach "the emulator ignored these bits" to the access it is about."""
    last = {}
    for e in events:
        if e["kind"] == "access":
            last[(e["peripheral"], e["offset"])] = e
        elif e["kind"] == "unmodelled":
            access = last.get((e["peripheral"], e["offset"]))
            if access is not None:
                access["unmodelled"] = {"bits": e["bits"], "tags": e["tags"]}


def _find_svd() -> Path | None:
    from .tools import svd_file
    if svd_file():
        return svd_file()
    renode = shutil.which("renode")
    if not renode:
        return None
    for candidate in (Path(renode).resolve().parent / "svd" / "STM32F40x.svd.gz",
                      Path("/opt/renode/svd/STM32F40x.svd.gz")):
        if candidate.is_file():
            return candidate
    return None


def write(trace: dict, out: Path) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    (out / "trace.json").write_text(json.dumps(trace))
